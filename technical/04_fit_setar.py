
import pandas as pd
from setar_model import SETAR
import numpy as np
import os
import logging

def fit_setar_garch(data_path, ar_order=4, delay=1, threshold_values=range(1, 5), log_file='technical/logs/04_setar.log'):
    """
    Fits a SETAR model to the conditional volatility from a GARCH model.

    Args:
        data_path (str): The path to the CSV file containing the conditional volatility.
        ar_order (int): The order of the autoregressive parameters.
        delay (int): The delay for the self-exciting threshold variable.
        threshold_values (range): A range of threshold values to test.
        log_file (str): The path to the log file.

    Returns:
        None
    """
    # Configure logging
    log_dir = os.path.dirname(log_file)
    if not os.path.exists(log_dir):
        os.makedirs(log_dir)
    logging.basicConfig(filename=log_file, level=logging.INFO, filemode='w',
                        format='%(asctime)s - %(levelname)s - %(message)s')

    # Load the conditional volatility data
    try:
        cond_vol = pd.read_csv(data_path, index_col=0, parse_dates=True)
        # Ensure the column name is 'conditional_volatility' or adapt if it's different
        cond_vol_series = cond_vol.squeeze()
    except FileNotFoundError:
        logging.error(f"Error: The file {data_path} was not found.")
        logging.error("Please run '03_find_best_garch.py' first to generate the conditional volatility data.")
        return

    best_threshold = None
    best_aic = float('inf')
    best_model_results = None

    logging.info("Finding best SETAR model...")
    for threshold in threshold_values:
        try:
            # Since the SETAR model from the gist doesn't support grid search for thresholds,
            # we manually iterate through the given threshold values.
            # The model is defined with 2 regimes, hence one threshold value.
            model = SETAR(cond_vol_series, order=2, ar_order=ar_order, delay=delay, thresholds=(threshold,))
            results = model.fit()
            
            # The custom SETAR model does not directly provide AIC/BIC.
            # We can use the OLS results' AIC.
            if results.aic < best_aic:
                best_aic = results.aic
                best_threshold = threshold
                best_model_results = results

        except Exception as e:
            logging.error(f"Error fitting SETAR with threshold {threshold}: {e}")
            continue

    if best_model_results:
        logging.info("\nBest SETAR Model Found:")
        logging.info(f"Threshold: {best_threshold}")
        logging.info(f"AIC: {best_aic}")
        logging.info(best_model_results.summary())
        
        # Storing the model for forecasting step
        # For simplicity, we'll just save the best threshold and parameters.
        # In a real application, you might serialize the model object.
        best_params = {
            'threshold': best_threshold,
            'ar_order': ar_order,
            'delay': delay,
            'params': best_model_results.params.tolist()
        }
        params_path = 'technical/best_setar_params.npy'
        np.save(params_path, best_params)
        logging.info(f"\nBest SETAR model parameters saved to '{params_path}'")


if __name__ == '__main__':
    # Path to the conditional volatility data generated by the GARCH script
    cv_data_path = 'technical/conditional_volatility.csv'
    fit_setar_garch(cv_data_path)
